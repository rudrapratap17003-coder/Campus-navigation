"""Accessibility assessment engine for campus locations, pathways, and routes.

Evaluates physical accessibility, multi-tier classification, and transparent
scoring heuristics for barrier-free college campus navigation.

DISCLAIMER:
The accessibility score (0-100) generated by this engine is an algorithmic
heuristic designed solely for comparative route optimization and navigation
assistance. It does NOT constitute an official, certified architectural,
ADA compliance, or regulatory safety rating.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

import networkx as nx

from modules.campus_map import CampusMap, load_campus_map
from modules.route_finder import RouteResult


class AccessibilityClassification(str, Enum):
    """Standardized classification categories for pathways and navigation routes."""

    FULLY_ACCESSIBLE = "Fully Accessible"
    ACCESSIBLE_WITH_ASSISTANCE = "Accessible with Assistance"
    NOT_WHEELCHAIR_ACCESSIBLE = "Not Wheelchair Accessible"
    TEMPORARILY_BLOCKED = "Temporarily Blocked"
    UNKNOWN_ACCESSIBILITY = "Unknown Accessibility"


def resolve_display_classification(classification: str, verification_status: str) -> str:
    """Map internal heuristic classification + verification metadata to standardized display label."""
    if classification == AccessibilityClassification.TEMPORARILY_BLOCKED.value:
        return "Temporarily Blocked"
    if classification == AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value:
        return "Inaccessible"
    if classification == AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value:
        return "Unknown"
    if classification == AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value:
        return "Accessible with Assistance"
    if classification == AccessibilityClassification.FULLY_ACCESSIBLE.value:
        if verification_status == "VERIFIED":
            return "Verified Accessible"
        if verification_status in ("IMAGE_DERIVED", "APPROXIMATE"):
            return "Imported Accessible"
        return "Imported Accessible (Unverified)"
    return classification


@dataclass
class PathAccessibilityAssessment:
    """Detailed accessibility assessment for a single pathway/connection."""

    source: str
    destination: str
    classification: str
    score: float
    distance: float
    estimated_time: float
    wheelchair_accessible: Optional[bool]
    has_stairs: bool
    has_ramp: bool
    has_elevator: bool
    status: str
    warnings: List[str] = field(default_factory=list)
    verification_status: str = "UNVERIFIED"
    display_classification: str = ""


@dataclass
class LocationAccessibilityAssessment:
    """Accessibility assessment for a specific campus location/node."""

    location_id: str
    name: str
    floor: int
    building: str
    category: str
    classification: str
    score: float
    total_connections: int
    accessible_connections: int
    has_accessible_restroom: bool
    is_elevator_hub: bool
    has_ramp_access: bool
    warnings: List[str] = field(default_factory=list)
    success: bool = True
    error_message: Optional[str] = None
    unknown_connections: int = 0
    verification_status: str = "UNVERIFIED"
    display_classification: str = ""


@dataclass
class RouteAccessibilityAssessment:
    """Comprehensive accessibility assessment for an entire navigation route."""

    path: List[str]
    overall_classification: str
    accessibility_score: float
    num_accessible_connections: int
    num_inaccessible_connections: int
    has_ramp: bool
    has_elevator: bool
    total_distance: float
    estimated_travel_time: float
    warnings: List[str] = field(default_factory=list)
    segment_evaluations: List[PathAccessibilityAssessment] = field(default_factory=list)
    success: bool = True
    error_message: Optional[str] = None
    verification_status: str = "UNVERIFIED"
    display_classification: str = ""
    num_unknown_connections: int = 0
    num_blocked_connections: int = 0


class AccessibilityEngine:
    """Evaluates physical barriers, assigns classifications, and calculates heuristic accessibility scores."""

    DISCLAIMER: str = (
        "Algorithmic heuristic score for route comparison only; not a certified architectural or safety rating."
    )

    def __init__(self, campus_map: Optional[Union[CampusMap, nx.Graph]] = None) -> None:
        """Initialize the engine with a CampusMap or NetworkX graph.

        Args:
            campus_map: Optional CampusMap or nx.Graph instance. If omitted, default dataset is loaded.
        """
        if campus_map is None:
            self.campus_map: Optional[CampusMap] = load_campus_map()
            self.graph: nx.Graph = self.campus_map.graph
        elif isinstance(campus_map, CampusMap):
            self.campus_map = campus_map
            self.graph = campus_map.graph
        elif isinstance(campus_map, nx.Graph):
            self.campus_map = None
            self.graph = campus_map
        else:
            raise TypeError("campus_map must be an instance of CampusMap or nx.Graph.")

    def _get_node_data(self, node_id: str) -> Dict[str, Any]:
        """Fetch node metadata safely."""
        if self.campus_map:
            loc = self.campus_map.get_location(node_id)
            if loc:
                return loc
        return dict(self.graph.nodes.get(node_id, {}))

    def _get_edge_data(self, source: str, destination: str) -> Optional[Dict[str, Any]]:
        """Fetch edge data between two nodes safely."""
        if not self.graph.has_edge(source, destination):
            return None
        return dict(self.graph.get_edge_data(source, destination) or {})

    def check_path_accessibility(
        self,
        source: str,
        destination: str,
        edge_data: Optional[Dict[str, Any]] = None,
    ) -> PathAccessibilityAssessment:
        """Classify and evaluate the accessibility of a single connection between two locations.

        Classification Rules:
        1. Temporarily Blocked: If path status is 'blocked', 'closed', or 'maintenance'.
        2. Unknown Accessibility: If accessibility flags are missing/None without physical attributes.
        3. Not Wheelchair Accessible: If staircase is present without lift/ramp, or wheelchair_accessible is False.
        4. Accessible with Assistance: If path requires manual assistance or is a steep/extended ramp.
        5. Fully Accessible: Step-free, verified wheelchair-accessible with open status.

        Args:
            source: Source location ID.
            destination: Destination location ID.
            edge_data: Optional explicit edge attribute dictionary.

        Returns:
            PathAccessibilityAssessment with classification, score, and warnings.
        """
        if edge_data is None:
            edge_data = self._get_edge_data(source, destination)
            if edge_data is None:
                return PathAccessibilityAssessment(
                    source=source,
                    destination=destination,
                    classification=AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value,
                    score=0.0,
                    distance=0.0,
                    estimated_time=0.0,
                    wheelchair_accessible=None,
                    has_stairs=False,
                    has_ramp=False,
                    has_elevator=False,
                    status="missing",
                    warnings=[f"Pathway '{source}' ↔ '{destination}' does not exist in active campus graph."],
                    verification_status="UNVERIFIED",
                    display_classification="Unknown",
                )

        warnings: List[str] = []
        status = str(edge_data.get("status", "open")).lower()
        dist = float(edge_data.get("distance", 0.0))
        est_time = float(edge_data.get("estimated_time", 0.0))
        verif_status = str(edge_data.get("verification_status", "UNVERIFIED"))

        u_name = str(self._get_node_data(source).get("name", source))
        v_name = str(self._get_node_data(destination).get("name", destination))

        wheelchair_val = edge_data.get("wheelchair_accessible")
        has_stairs = bool(edge_data.get("has_stairs", False))
        has_ramp = bool(edge_data.get("has_ramp", False))
        has_elevator = bool(edge_data.get("has_elevator", False))
        steep_incline = bool(edge_data.get("steep_incline", False))
        manual_flag = bool(
            edge_data.get("accessible_with_assistance", False)
            or edge_data.get("requires_assistance", False)
        )
        long_ramp = has_ramp and dist >= 35.0
        requires_assistance = manual_flag or steep_incline or long_ramp

        # 1. Check if temporarily blocked
        if status in ("blocked", "closed", "maintenance", "under_maintenance"):
            warnings.append(
                f"Pathway '{u_name}' ↔ '{v_name}' ({source} ↔ {destination}) is currently closed or blocked (status: '{status}')."
            )
            cls_val = AccessibilityClassification.TEMPORARILY_BLOCKED.value
            return PathAccessibilityAssessment(
                source=source,
                destination=destination,
                classification=cls_val,
                score=0.0,
                distance=dist,
                estimated_time=est_time,
                wheelchair_accessible=bool(wheelchair_val) if wheelchair_val is not None else None,
                has_stairs=has_stairs,
                has_ramp=has_ramp,
                has_elevator=has_elevator,
                status=status,
                warnings=warnings,
                verification_status=verif_status,
                display_classification=resolve_display_classification(cls_val, verif_status),
            )

        # 2. Check for unknown accessibility
        if wheelchair_val is None and not has_ramp and not has_elevator and not has_stairs:
            warnings.append(
                f"Pathway '{u_name}' ↔ '{v_name}' ({source} ↔ {destination}) accessibility information is missing or unverified."
            )
            cls_val = AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value
            return PathAccessibilityAssessment(
                source=source,
                destination=destination,
                classification=cls_val,
                score=50.0,
                distance=dist,
                estimated_time=est_time,
                wheelchair_accessible=None,
                has_stairs=has_stairs,
                has_ramp=has_ramp,
                has_elevator=has_elevator,
                status=status,
                warnings=warnings,
                verification_status=verif_status,
                display_classification=resolve_display_classification(cls_val, verif_status),
            )

        # 3. Check for staircase barrier without elevator/ramp
        if (has_stairs and not has_elevator and not has_ramp) or wheelchair_val is False:
            warnings.append(
                f"Pathway '{u_name}' ↔ '{v_name}' ({source} ↔ {destination}) contains stairs or is marked inaccessible for wheelchairs."
            )
            cls_val = AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value
            return PathAccessibilityAssessment(
                source=source,
                destination=destination,
                classification=cls_val,
                score=15.0,
                distance=dist,
                estimated_time=est_time,
                wheelchair_accessible=False,
                has_stairs=has_stairs,
                has_ramp=has_ramp,
                has_elevator=has_elevator,
                status=status,
                warnings=warnings,
                verification_status=verif_status,
                display_classification=resolve_display_classification(cls_val, verif_status),
            )

        # 4. Check for accessible with assistance
        if requires_assistance:
            reasons = []
            if long_ramp:
                reasons.append(f"extended ramp run ({dist:.1f} m >= 35.0 m heuristic threshold)")
            if steep_incline:
                reasons.append("steep incline gradient")
            if manual_flag:
                reasons.append("manual assistance flag in pathway metadata")
            reason_str = ", ".join(reasons) if reasons else "assistance requirement"
            warnings.append(
                f"Segment '{u_name}' ↔ '{v_name}' ({source} ↔ {destination}) is wheelchair passable "
                f"but may require manual assistance due to {reason_str} (data status: {verif_status})."
            )
            score = 75.0
            if has_ramp:
                score += 5.0
            cls_val = AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value
            return PathAccessibilityAssessment(
                source=source,
                destination=destination,
                classification=cls_val,
                score=min(85.0, score),
                distance=dist,
                estimated_time=est_time,
                wheelchair_accessible=True,
                has_stairs=has_stairs,
                has_ramp=has_ramp,
                has_elevator=has_elevator,
                status=status,
                warnings=warnings,
                verification_status=verif_status,
                display_classification=resolve_display_classification(cls_val, verif_status),
            )

        # 5. Fully accessible
        score = 100.0
        if has_elevator:
            score = 100.0
        elif has_ramp:
            score = 100.0

        cls_val = AccessibilityClassification.FULLY_ACCESSIBLE.value
        return PathAccessibilityAssessment(
            source=source,
            destination=destination,
            classification=cls_val,
            score=score,
            distance=dist,
            estimated_time=est_time,
            wheelchair_accessible=True,
            has_stairs=False,
            has_ramp=has_ramp,
            has_elevator=has_elevator,
            status=status,
            warnings=warnings,
            verification_status=verif_status,
            display_classification=resolve_display_classification(cls_val, verif_status),
        )

    def check_location_accessibility(self, location_id: str) -> LocationAccessibilityAssessment:
        """Evaluate the accessibility characteristics of a specific campus node.

        Args:
            location_id: Unique identifier of the location.

        Returns:
            LocationAccessibilityAssessment object.
        """
        if location_id not in self.graph:
            return LocationAccessibilityAssessment(
                location_id=location_id,
                name="Unknown",
                floor=0,
                building="Unknown",
                category="Unknown",
                classification=AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value,
                score=0.0,
                total_connections=0,
                accessible_connections=0,
                has_accessible_restroom=False,
                is_elevator_hub=False,
                has_ramp_access=False,
                warnings=[f"Location ID '{location_id}' not found in campus network."],
                success=False,
                error_message=f"Location '{location_id}' does not exist.",
            )

        node_data = self._get_node_data(location_id)
        name = str(node_data.get("name", location_id))
        floor = int(node_data.get("floor", 0))
        building = str(node_data.get("building", ""))
        category = str(node_data.get("category", "")).lower()
        verif_status = str(node_data.get("verification_status", "UNVERIFIED"))

        warnings: List[str] = []
        has_accessible_restroom = category == "restroom" and "accessible" in name.lower()
        is_elevator_hub = category == "elevator"
        has_ramp_access = "ramp" in name.lower() or category == "ramp"

        neighbors = list(self.graph.neighbors(location_id))
        total_connections = len(neighbors)
        accessible_connections = 0
        unknown_connections = 0
        blocked_connections = 0
        connection_scores: List[float] = []

        for neighbor in neighbors:
            edge_data = self.graph.get_edge_data(location_id, neighbor) or {}
            assessment = self.check_path_accessibility(location_id, neighbor, edge_data)
            connection_scores.append(assessment.score)
            if assessment.classification in (
                AccessibilityClassification.FULLY_ACCESSIBLE.value,
                AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value,
            ):
                accessible_connections += 1
            elif assessment.classification == AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value:
                unknown_connections += 1
            elif assessment.classification == AccessibilityClassification.TEMPORARILY_BLOCKED.value:
                blocked_connections += 1

        if total_connections == 0:
            classification = AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value if node_data.get("wheelchair_accessible") is None else AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value
            score = 0.0
            warnings.append("Location is currently isolated with zero connected pathways.")
        else:
            avg_conn_score = sum(connection_scores) / total_connections
            score = avg_conn_score

            # Amenity bonus only when location has at least one accessible connection
            if accessible_connections > 0 and (has_accessible_restroom or is_elevator_hub or has_ramp_access):
                score = min(100.0, score + 10.0)

            if accessible_connections == total_connections:
                classification = AccessibilityClassification.FULLY_ACCESSIBLE.value
            elif accessible_connections > 0:
                classification = AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value
                if unknown_connections > 0:
                    warnings.append(f"{unknown_connections} adjacent pathway(s) have unknown/unverified accessibility.")
                if total_connections - accessible_connections - unknown_connections > 0:
                    warnings.append("Some adjacent pathways contain stairs, barriers, or temporary closures.")
            elif unknown_connections == total_connections:
                classification = AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value
                warnings.append("All connected pathways lack verified accessibility information.")
            elif blocked_connections == total_connections:
                classification = AccessibilityClassification.TEMPORARILY_BLOCKED.value
                warnings.append("All connected pathways are temporarily blocked.")
            else:
                classification = AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value
                warnings.append("All connected pathways from this location have stairs or confirmed barriers.")

        return LocationAccessibilityAssessment(
            location_id=location_id,
            name=name,
            floor=floor,
            building=building,
            category=category,
            classification=classification,
            score=round(score, 1),
            total_connections=total_connections,
            accessible_connections=accessible_connections,
            has_accessible_restroom=has_accessible_restroom,
            is_elevator_hub=is_elevator_hub,
            has_ramp_access=has_ramp_access,
            warnings=warnings,
            success=True,
            unknown_connections=unknown_connections,
            verification_status=verif_status,
            display_classification=resolve_display_classification(classification, verif_status),
        )

    def calculate_accessibility_score(
        self,
        route_or_edge: Union[List[str], RouteResult, Dict[str, Any], Tuple[str, str]],
    ) -> float:
        """Compute the heuristic accessibility score (0 to 100) for a route, path, or edge dictionary.

        Scoring Formula:
        For a multi-segment route with segment distances d_i and segment scores s_i:
            Raw Score = sum(d_i * s_i) / sum(d_i)
        Bottleneck Rules:
        - If any segment is Temporarily Blocked: route score is capped at min(Raw Score, 20.0).
        - If any segment is Not Wheelchair Accessible (e.g. stairs): route score is capped at min(Raw Score, 40.0).
        - If any segment has Unknown Accessibility: route score is capped at min(Raw Score, 75.0).
        """
        # Handle dictionary input
        if isinstance(route_or_edge, dict):
            assessment = self.check_path_accessibility("u", "v", route_or_edge)
            return assessment.score

        # Handle tuple of two node IDs
        if isinstance(route_or_edge, tuple) and len(route_or_edge) == 2:
            assessment = self.check_path_accessibility(route_or_edge[0], route_or_edge[1])
            return assessment.score

        # Handle RouteResult or List of node IDs
        path = route_or_edge.path if isinstance(route_or_edge, RouteResult) else list(route_or_edge)

        if not path or len(path) < 2:
            return 100.0 if len(path) == 1 else 0.0

        segment_scores: List[float] = []
        segment_weights: List[float] = []
        has_blocked = False
        has_inaccessible = False
        has_unknown = False

        for i in range(len(path) - 1):
            u, v = path[i], path[i + 1]
            edge_data = self._get_edge_data(u, v) or {}
            assessment = self.check_path_accessibility(u, v, edge_data)

            dist = max(1.0, assessment.distance)
            segment_scores.append(assessment.score)
            segment_weights.append(dist)

            if assessment.classification == AccessibilityClassification.TEMPORARILY_BLOCKED.value:
                has_blocked = True
            elif assessment.classification == AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value:
                has_inaccessible = True
            elif assessment.classification == AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value:
                has_unknown = True

        total_weight = sum(segment_weights)
        raw_score = (
            sum(s * w for s, w in zip(segment_scores, segment_weights)) / total_weight
            if total_weight > 0
            else 0.0
        )

        final_score = raw_score
        if has_blocked:
            final_score = min(final_score, 20.0)
        elif has_inaccessible:
            final_score = min(final_score, 40.0)
        elif has_unknown:
            final_score = min(final_score, 75.0)

        return round(final_score, 1)

    def evaluate_route_accessibility(
        self,
        route: Union[List[str], RouteResult],
    ) -> RouteAccessibilityAssessment:
        """Perform a comprehensive accessibility audit for an entire navigation route.

        Args:
            route: Either a RouteResult object or a list of location IDs.

        Returns:
            RouteAccessibilityAssessment with full accessibility metrics, warnings, and classification.
        """
        path = route.path if isinstance(route, RouteResult) else list(route)

        if not path:
            return RouteAccessibilityAssessment(
                path=[],
                overall_classification=AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value,
                accessibility_score=0.0,
                num_accessible_connections=0,
                num_inaccessible_connections=0,
                has_ramp=False,
                has_elevator=False,
                total_distance=0.0,
                estimated_travel_time=0.0,
                warnings=["Route is empty."],
                success=False,
                error_message="Cannot evaluate an empty route.",
            )

        if len(path) == 1:
            loc_assessment = self.check_location_accessibility(path[0])
            return RouteAccessibilityAssessment(
                path=path,
                overall_classification=loc_assessment.classification,
                accessibility_score=loc_assessment.score,
                num_accessible_connections=0,
                num_inaccessible_connections=0,
                has_ramp=loc_assessment.has_ramp_access,
                has_elevator=loc_assessment.is_elevator_hub,
                total_distance=0.0,
                estimated_travel_time=0.0,
                warnings=["Route origin is identical to destination."],
                success=True,
            )

        segment_evaluations: List[PathAccessibilityAssessment] = []
        num_accessible = 0
        num_inaccessible = 0
        num_unknown = 0
        num_blocked = 0
        has_ramp = False
        has_elevator = False
        total_dist = 0.0
        total_time = 0.0
        warnings: List[str] = []

        has_blocked_seg = False
        has_stairs_seg = False
        has_assistance_seg = False
        has_unknown_seg = False
        verif_statuses: List[str] = []

        for i in range(len(path) - 1):
            u, v = path[i], path[i + 1]
            edge_data = self._get_edge_data(u, v)

            if edge_data is None:
                warnings.append(f"Connection between '{u}' and '{v}' does not exist in active graph.")
                num_inaccessible += 1
                has_unknown_seg = True
                continue

            assessment = self.check_path_accessibility(u, v, edge_data)
            segment_evaluations.append(assessment)
            verif_statuses.append(assessment.verification_status)

            total_dist += assessment.distance
            total_time += assessment.estimated_time

            if assessment.has_ramp:
                has_ramp = True
            if assessment.has_elevator:
                has_elevator = True

            if assessment.classification == AccessibilityClassification.FULLY_ACCESSIBLE.value:
                num_accessible += 1
            elif assessment.classification == AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value:
                num_accessible += 1
                has_assistance_seg = True
            elif assessment.classification == AccessibilityClassification.TEMPORARILY_BLOCKED.value:
                num_inaccessible += 1
                num_blocked += 1
                has_blocked_seg = True
            elif assessment.classification == AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value:
                num_inaccessible += 1
                has_stairs_seg = True
            elif assessment.classification == AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value:
                num_unknown += 1
                has_unknown_seg = True

            for w in assessment.warnings:
                if w not in warnings:
                    warnings.append(w)

        score = self.calculate_accessibility_score(path)

        # Determine overall verification status (conservative weakest-link)
        if not verif_statuses:
            route_verif = "UNVERIFIED"
        elif all(s == "VERIFIED" for s in verif_statuses):
            route_verif = "VERIFIED"
        elif any(s == "UNVERIFIED" for s in verif_statuses):
            route_verif = "UNVERIFIED"
        elif any(s == "APPROXIMATE" for s in verif_statuses):
            route_verif = "APPROXIMATE"
        else:
            route_verif = "IMAGE_DERIVED"

        # Determine overall route classification with clear explanations
        if has_blocked_seg:
            overall_classification = AccessibilityClassification.TEMPORARILY_BLOCKED.value
            warnings.append("Route cannot be traversed because one or more pathways are temporarily blocked.")
        elif has_stairs_seg:
            overall_classification = AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value
            warnings.append("Route contains stairs and is not wheelchair accessible; toggle Wheelchair mode to reroute via elevator.")
        elif has_unknown_seg:
            overall_classification = AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value
            warnings.append("Route contains unverified segments with missing accessibility metadata.")
        elif has_assistance_seg:
            overall_classification = AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value
            assist_segs = [
                f"{se.source} ↔ {se.destination} ({se.distance:.1f} m)"
                for se in segment_evaluations
                if se.classification == AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value
            ]
            warnings.append(
                f"Overall heuristic score is {score}/100 across {len(segment_evaluations)} segments, "
                f"but manual-assistance advisory applies to: {', '.join(assist_segs)}."
            )
        else:
            overall_classification = AccessibilityClassification.FULLY_ACCESSIBLE.value

        return RouteAccessibilityAssessment(
            path=path,
            overall_classification=overall_classification,
            accessibility_score=score,
            num_accessible_connections=num_accessible,
            num_inaccessible_connections=num_inaccessible,
            has_ramp=has_ramp,
            has_elevator=has_elevator,
            total_distance=round(total_dist, 2),
            estimated_travel_time=round(total_time, 2),
            warnings=warnings,
            segment_evaluations=segment_evaluations,
            success=True,
            verification_status=route_verif,
            display_classification=resolve_display_classification(overall_classification, route_verif),
            num_unknown_connections=num_unknown,
            num_blocked_connections=num_blocked,
        )

    def get_accessibility_summary(self) -> Dict[str, Any]:
        """Aggregate campus-wide accessibility statistics across all nodes and edges."""
        total_locations = self.graph.number_of_nodes()
        total_pathways = self.graph.number_of_edges()

        classification_counts: Dict[str, int] = {
            AccessibilityClassification.FULLY_ACCESSIBLE.value: 0,
            AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value: 0,
            AccessibilityClassification.NOT_WHEELCHAIR_ACCESSIBLE.value: 0,
            AccessibilityClassification.TEMPORARILY_BLOCKED.value: 0,
            AccessibilityClassification.UNKNOWN_ACCESSIBILITY.value: 0,
        }

        elevator_edges = 0
        ramp_edges = 0
        stairs_edges = 0
        pathway_scores: List[float] = []

        for u, v in self.graph.edges():
            edge_data = self.graph.get_edge_data(u, v) or {}
            assessment = self.check_path_accessibility(u, v, edge_data)
            classification_counts[assessment.classification] = (
                classification_counts.get(assessment.classification, 0) + 1
            )
            pathway_scores.append(assessment.score)

            if assessment.has_elevator:
                elevator_edges += 1
            if assessment.has_ramp:
                ramp_edges += 1
            if assessment.has_stairs:
                stairs_edges += 1

        accessible_pathways = (
            classification_counts[AccessibilityClassification.FULLY_ACCESSIBLE.value]
            + classification_counts[AccessibilityClassification.ACCESSIBLE_WITH_ASSISTANCE.value]
        )

        avg_score = (
            round(sum(pathway_scores) / len(pathway_scores), 1) if pathway_scores else 0.0
        )
        network_pct = (
            round((accessible_pathways / total_pathways) * 100, 1) if total_pathways > 0 else 0.0
        )

        return {
            "total_locations": total_locations,
            "total_pathways": total_pathways,
            "classification_counts": classification_counts,
            "accessible_pathways": accessible_pathways,
            "inaccessible_pathways": total_pathways - accessible_pathways,
            "elevator_pathways": elevator_edges,
            "ramp_pathways": ramp_edges,
            "stairs_pathways": stairs_edges,
            "average_pathway_score": avg_score,
            "network_accessibility_percentage": network_pct,
            "disclaimer": self.DISCLAIMER,
        }
